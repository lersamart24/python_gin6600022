# Kelvin → Fahrenheit
kalvin = input("Can you enter your kalvin: ")
kalvin_float = float(kalvin)
fahrenheit = 1.8 * (kalvin_float - 273.15) + 32.0
print("Your temperature is", fahrenheit, "fahrenheit")

